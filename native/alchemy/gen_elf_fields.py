#!/usr/bin/env python3
"""Generate igb_elf_fields.cpp from tools/igb_elf_classes.json (class registry decoded from the ELF).

The .IGB file itself carries every class's field layout (type, ordinal, size); only the field *names*
come from the ELF registration tables (FUN_00318080 call sites).  Run from the repo root:
    python -I native/alchemy/gen_elf_fields.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
src = os.path.join(ROOT, 'tools', 'igb_elf_classes.json')
dst = os.path.join(ROOT, 'native', 'alchemy', 'igb_elf_fields.cpp')
with open(src, 'r', encoding='utf-8') as f:
    classes = json.load(f)
lines = ['// GENERATED by native/alchemy/gen_elf_fields.py from tools/igb_elf_classes.json -- do not edit.',
         '// Class registry decoded from SLUS_217.14 (672 FUN_00318b00 registration sites); field names in',
         '// registration order (FUN_00318080), types as metafield class names.',
         '#include "alchemy/igb_elf_fields.hpp"',
         'namespace baroque::alchemy::elf {',
         'namespace {']
for name in sorted(classes):
    c = classes[name]
    fields = c['fields']
    if fields:
        lines.append('const FieldDef k_%s[] = {' % name)
        for fd in fields:
            lines.append('    {"%s", "%s", %d},' % (fd['name'], fd['type'], fd['offset']))
        lines.append('};')
lines.append('const ClassDef k_classes[] = {')
for name in sorted(classes):
    c = classes[name]
    n = len(c['fields'])
    arr = 'k_%s' % name if n else 'nullptr'
    parent = '"%s"' % c['parent'] if c.get('parent') else 'nullptr'
    lines.append('    {"%s", %s, %d, %s, %d},' % (name, parent, c.get('size') or 0, arr, n))
lines.append('};')
lines.append('}  // namespace')
lines.append('const ClassDef* findClass(std::string_view name) {')
lines.append('    for (const ClassDef& c : k_classes) if (name == c.name) return &c;')
lines.append('    return nullptr;')
lines.append('}')
lines.append('std::size_t classCount() { return sizeof(k_classes) / sizeof(k_classes[0]); }')
lines.append('}  // namespace baroque::alchemy::elf')
with open(dst, 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(lines) + '\n')
print('wrote', dst, len(classes), 'classes')
