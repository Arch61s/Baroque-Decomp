"""Extract the sprite layout tables of the Item Screen 0x517b60 (FUN_00153790 frame, FUN_00155500 list panel,
FUN_00155970 page tabs, FUN_00152a00 context menu, FUN_001524b0 stat digits) from SLUS_217.14 into
native/game/items/item_screen_tables.inc.

Usage: python -I tools/gen_item_screen_tables.py
Floats are emitted bit-exact (hex float literals where not integral). Rect tables are {x, y, w, h}, UV tables are
{u0, v0, u1, v1} in texels of the 128x128 TEX_UI sheets (FUN_00166820 stack arguments texW = texH = 128, read from
the disassembly of every caller).
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import disasm  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'native', 'game', 'items', 'item_screen_tables.inc')


def f32(addr):
    return struct.unpack('<f', struct.pack('<I', disasm.word(addr)))[0]


def fmt_float(v):
    if v == int(v) and abs(v) < 1e7:
        return '%d.0f' % int(v)
    return '%sf' % float.hex(v)


def table(L, name, addr, dims, comment):
    n = 1
    for d in dims:
        n *= d
    L.append('// %s: %s floats at 0x%06x (%s)' % (name, ' x '.join(str(d) for d in dims), addr, comment))
    vals = [fmt_float(f32(addr + i * 4)) for i in range(n)]

    def emit(level, off, indent):
        if level == len(dims) - 1:
            return '{' + ', '.join(vals[off:off + dims[level]]) + '}'
        stride = 1
        for d in dims[level + 1:]:
            stride *= d
        inner = [emit(level + 1, off + k * stride, indent + 4) for k in range(dims[level])]
        if level == 0:
            return '{\n' + ''.join(' ' * (indent + 4) + s + ',\n' for s in inner) + ' ' * indent + '}'
        return '{' + ', '.join(inner) + '}'

    L.append('inline constexpr float %s%s = %s;' % (name, ''.join('[%d]' % d for d in dims), emit(0, 0, 0)))


def main():
    L = ['// Generated by tools/gen_item_screen_tables.py from SLUS_217.14. Do not edit.',
         '// Item Screen 0x517b60 sprite layout tables (rects {x, y, w, h}; UVs {u0, v0, u1, v1} in texels / 128).',
         '// clang-format off']
    table(L, 'kIsFrameRect', 0x48f850, [32, 4], 'FUN_00153790 32 frame pieces TEX_UI02, x-1 / y-1')
    table(L, 'kIsFrameUv', 0x48fa50, [32, 4], 'their UVs')
    table(L, 'kIsFrameVarRect', 0x48fc50, [8, 4, 4], 'FUN_00153790 8 pieces x 4 hint variants (+0x54) TEX_UI02')
    table(L, 'kIsFrameVarUv', 0x48fe50, [8, 4], 'their UVs')
    table(L, 'kIsFrame03Rect', 0x48fed0, [4, 4], 'FUN_00153790 4 pieces TEX_UI03')
    table(L, 'kIsFrame03Uv', 0x48ff10, [4, 4], 'their UVs')
    table(L, 'kIsHintRect', 0x48ff50, [2, 4], 'FUN_00153790 L1 / R1 hint glyphs TEX_UI04')
    table(L, 'kIsHintUv', 0x48ff70, [2, 4], 'their UVs')
    table(L, 'kIsExpDigitRect', 0x48f6e0, [13, 4], 'FUN_001524b0 EXP digits TEX_UI00')
    table(L, 'kIsStatDigitRect', 0x48f7b0, [10, 4], 'FUN_001524b0 ATK digits (DEF: y + 18) TEX_UI00')
    table(L, 'kIsPanelRect', 0x490aa0, [56, 4], 'FUN_00155500 56 panel pieces TEX_UI03 (no -1 offset)')
    table(L, 'kIsPanelUv', 0x490e20, [56, 4], 'their UVs')
    table(L, 'kIsPanel2Rect', 0x4911a0, [18, 2, 4], 'FUN_00155500 18 pieces TEX_UI03, [i][+0x58 != 1]')
    table(L, 'kIsPanel2Uv', 0x4913e0, [18, 4], 'their UVs')
    table(L, 'kIsTabRect', 0x491500, [5, 4], 'FUN_00155970 page tabs TEX_UI03 z -0.7')
    table(L, 'kIsTabUv', 0x491550, [5, 2, 4], 'FUN_001591e0 tab UVs [tab][current]')
    table(L, 'kIsArrowRect', 0x4915f0, [2, 4], 'FUN_00155500 page arrows TEX_UI03')
    table(L, 'kIsArrowUv', 0x491610, [2, 2, 4], 'FUN_001591e0 arrow UVs [arrow][lit]')
    table(L, 'kIsCtxRect', 0x491650, [24, 12], 'FUN_00152a00 24 context-menu pieces TEX_UI04 (first 4 used, x-1 / y-1)')
    table(L, 'kIsCtxUv', 0x491ad0, [24, 4], 'their UVs')
    L.append('// clang-format on')
    with open(OUT, 'w', newline='\n') as f:
        f.write('\n'.join(L) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
