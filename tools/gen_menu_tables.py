"""Extract the data tables used by the translated menu pages (NAME ENTRY, FILE_SELECT, KEY ASSIGN, BRIGHTNESS,
OPTION database pages) from SLUS_217.14 into native/game/ui/menu_tables.inc.

Usage: python -I tools/gen_menu_tables.py
All values are emitted verbatim: floats bit-exact (hex float literals), Shift-JIS strings as octal escapes.
Tables already emitted by tools/gen_strings.py into ui_tables.inc are not repeated here.
"""
import os
import struct
