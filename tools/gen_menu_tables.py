LO, HI = 0x100000, 0x4e5b70


def f32(addr):
    return struct.unpack('<f', struct.pack('<I', disasm.word(addr)))[0]


def fmt_float(v):
    if v == int(v) and abs(v) < 1e7:
        return '%d.0f' % int(v)
    return '%sf' % float.hex(v)


def c_escape(b):
    out = []
    for ch in b:
        if ch == 0x22:
            out.append('\\"')
        elif ch == 0x5c:
            out.append('\\\\')
        elif 0x20 <= ch < 0x7f:
            out.append(chr(ch))
        else:
            out.append('\\%03o' % ch)
    return '"' + ''.join(out) + '"'


def cstr(addr):
    return disasm.read_bytes(addr, 64).split(b'\0')[0]


def floats(L, name, addr, rows, cols, comment):
    L.append('// %s: %d x %d floats at 0x%06x (%s)' % (name, rows, cols, addr, comment))
    L.append('BAROQUE_TABLE_LINKAGE const float %s[%d][%d] = {' % (name, rows, cols))
    for r in range(rows):
        L.append('    {%s},' % ', '.join(fmt_float(f32(addr + (r * cols + c) * 4)) for c in range(cols)))
    L.append('};')


def flat_floats(L, name, addr, count, comment):
    L.append('// %s: %d floats at 0x%06x (%s)' % (name, count, addr, comment))
    L.append('BAROQUE_TABLE_LINKAGE const float %s[%d] = {%s};' %
             (name, count, ', '.join(fmt_float(f32(addr + i * 4)) for i in range(count))))


def words(L, name, addr, count, comment, ctype='unsigned int'):
    L.append('// %s: %d words at 0x%06x (%s)' % (name, count, addr, comment))
    vals = []
    for i in range(count):
        w = disasm.word(addr + i * 4)
        if ctype == 'int' and w >= 0x80000000:
            vals.append('%d' % (w - 0x100000000))
        else:
            vals.append('0x%x' % w)
    L.append('BAROQUE_TABLE_LINKAGE const %s %s[%d] = {%s};' % (ctype, name, count, ', '.join(vals)))


