"""Emit the talk-condition predicates and progression tables of SLUS_217.14 for native/game/progress.

Usage: python -I tools/gen_progress_tables.py
Outputs (regenerated, never hand-edited):
  native/game/progress/talk_predicates.inc   the 81 per-block predicate functions dispatched by FUN_001a0e60
                                             (FUN_0017c700 .. FUN_001a0e50), lifted from the MIPS: every case of
                                             every jump table (0x496ef0..) is symbolically executed; the only call
                                             in the whole range is FUN_00178a80(0x53c3b0, id) (flag test), so each
                                             case is a decision tree over flag tests and is emitted as if/return.
  native/game/progress/talk_tables.inc       condition table 0x45bac0, speaker start table 0x461f80, 4-char ids
                                             used by FUN_001a69e0 / FUN_001a3cc0, item-id list 0x4623c0 + 0x498870
  native/game/progress/flag_tables.inc       counter table 0x496b50 and its threshold tables, flag reset lists of
                                             FUN_00178b30, keep lists 0x496230/0x496ee8, achievement pairs 0x48ca50,
                                             database stage table 0x499650, save magic/dir name
  native/checks/progress_expected.inc        expected predicate results for the check's flag states, computed by
                                             a concrete MIPS interpreter (independent of the lifted code path)

Self-checks (assert): every case terminates; the decision tree agrees with the concrete interpreter on random flag
states; every flag id is < 4000 (0x7d words).
"""
import os
