OUT = os.path.join(ROOT, 'native', 'game', 'progress')
CHECKS = os.path.join(ROOT, 'native', 'checks')
HEADER = '// GENERATED by tools/gen_progress_tables.py from SLUS_217.14 - do not edit.\n'
w = disasm.word
FLAG_MGR = 0x53c3b0
FLAG_TEST = 0x178a80
TALK_COUNT = 0x636

rabbitizer.config.regNames_gprAbiNames = rabbitizer.Abi.O32


def ins_at(a):
    return rabbitizer.Instruction(w(a), a, category=rabbitizer.InstrCategory.R5900)


def s16(v):
    return v - 0x10000 if v & 0x8000 else v


# ---------------------------------------------------------------- predicate block functions (FUN_001a0e60)
def dispatch_funcs():
    """Walk FUN_001a0e60's compare chain: (limit, target) pairs, read from the instructions."""
    # The chain compares a0 with increasing limits (slti, the next one often in a beql delay slot) and calls one
    # block function per limit, so the k-th slti immediate pairs with the k-th jal target.
    limits = []
    targets = []
    a = 0x1a0e60
    while len(targets) < 81:
        i = ins_at(a)
        n = i.getOpcodeName()
        if n == 'slti':
            limits.append(s16(w(a) & 0xffff))
        if n == 'jal':
            targets.append(i.getInstrIndexAsVram())
        a += 4
    assert limits == sorted(limits) and len(limits) >= 81, limits
    return list(zip(limits[:81], targets))


def parse_prologue(f):
    """Return (base, count, table) of a predicate block function, or None for a plain 'return 0'."""
    base = 0
    count = None
    hi = lo = None
    a = f
    for _ in range(12):
        i = ins_at(a)
        n = i.getOpcodeName()
        ops = i.disassemble()
        if n == 'addiu' and '$v0, $a0' in ops:
            base = -s16(w(a) & 0xffff)
        elif n == 'sltiu':
            count = w(a) & 0xffff
        elif n == 'lui' and '$v1' in ops:
            hi = (w(a) & 0xffff) << 16
        elif n == 'addiu' and '$v1, $v1' in ops:
            lo = s16(w(a) & 0xffff)
        elif n == 'jr' and '$v0' in ops:
            break
        elif n == 'jr':
            return None
        a += 4
    assert count is not None and hi is not None and lo is not None, hex(f)
    return base, count, (hi + lo) & 0xffffffff


REG = {2: 'v0', 3: 'v1', 4: 'a0', 5: 'a1', 1: 'at', 0: 'zero'}


class Sym:
    """v0 after a flag test: the boolean result of FUN_00178a80(mgr, flag)."""
    def __init__(self, flag):
        self.flag = flag

    def __eq__(self, o):
        return isinstance(o, Sym) and o.flag == self.flag

    def __hash__(self):
        return hash(('sym', self.flag))


def step_simple(i, regs):
    """Execute a non-branch instruction on a register dict. Returns False when not handled."""
    n = i.getOpcodeName()
    raw = i.getRaw() if hasattr(i, 'getRaw') else None
    word_ = w(i.vram)
    rs = (word_ >> 21) & 31
    rt = (word_ >> 16) & 31
    rd = (word_ >> 11) & 31
    imm = word_ & 0xffff
    del raw
    if n == 'nop':
        return True
    if n == 'lui':
        regs[rt] = (imm << 16) & 0xffffffff
        return True
    if n == 'addiu':
        if rt == 29:   # sp
            return True
        src = 0 if rs == 0 else regs.get(rs)
        assert isinstance(src, int), (hex(i.vram), i.disassemble(), src)
        regs[rt] = (src + s16(imm)) & 0xffffffff
        return True
    if n == 'daddu':
        assert (word_ >> 16) & 31 == 0 or rs == 0, i.disassemble()
        src = rs if rs != 0 else rt
        regs[rd] = 0 if src == 0 else regs.get(src)
        return True
    if n in ('sd', 'ld'):
        return True
    return False


def run_case(entry, flag_oracle=None):
    """Symbolic (flag_oracle None) or concrete execution of one jump-table case starting at `entry`.
    Symbolic: returns a decision tree. Concrete: returns the int result."""
    memo = {}

    def go(pc, regs):
        key = (pc, tuple(sorted((k, v if isinstance(v, int) else ('s', v.flag)) for k, v in regs.items())))
        if flag_oracle is None and key in memo:
            return memo[key]
        regs = dict(regs)
        steps = 0
        while True:
            steps += 1
            assert steps < 4000, hex(pc)
            i = ins_at(pc)
            n = i.getOpcodeName()
            if step_simple(i, regs):
                pc += 4
                continue
            word_ = w(pc)
            rs = (word_ >> 21) & 31
            rt = (word_ >> 16) & 31
            if n == 'jal':
                tgt = i.getInstrIndexAsVram()
                assert tgt == FLAG_TEST, hex(pc)
                d = ins_at(pc + 4)
                assert step_simple(d, regs), hex(pc + 4)
                assert regs.get(4) == FLAG_MGR, (hex(pc), regs.get(4))
                flag = regs.get(5)
                assert isinstance(flag, int) and 0 <= flag < 4000, (hex(pc), flag)
                regs[2] = Sym(flag) if flag_oracle is None else int(flag_oracle(flag))
                pc += 8
                continue
            if n == 'jr':
                assert rs == 31, hex(pc)
                d = ins_at(pc + 4)
                assert step_simple(d, regs), hex(pc + 4)
                v = regs.get(2)
                res = ('ret', v.flag if isinstance(v, Sym) else v, isinstance(v, Sym))
                if flag_oracle is not None:
                    return (v if isinstance(v, int) else int(flag_oracle(v.flag)))
                memo[key] = res
                return res
            if n in ('b', 'beqz', 'bnez', 'beql', 'bnel', 'beq', 'bne'):
                tgt = (pc + 4 + (s16(word_ & 0xffff) << 2)) & 0xffffffff
                likely = n in ('beql', 'bnel')
                if n == 'b':
                    d = ins_at(pc + 4)
                    assert step_simple(d, regs), hex(pc + 4)
                    pc = tgt
                    continue
                if n in ('beq', 'bne', 'beql', 'bnel'):
                    assert rt == 0, (hex(pc), i.disassemble())
                val = regs.get(rs)
                want_zero = n in ('beqz', 'beq', 'beql')
                if isinstance(val, int):
                    taken = (val == 0) if want_zero else (val != 0)
                    d = ins_at(pc + 4)
                    if taken or not likely:
                        assert step_simple(d, regs), hex(pc + 4)
                    pc = tgt if taken else pc + 8
                    continue
                assert isinstance(val, Sym), (hex(pc), val)
                # fork on the flag value
                results = {}
                for fv in (0, 1):
                    r2 = dict(regs)
                    r2[rs] = fv
                    taken = (fv == 0) if want_zero else (fv != 0)
                    d = ins_at(pc + 4)
                    if taken or not likely:
                        assert step_simple(d, r2), hex(pc + 4)
                    results[fv] = go(tgt if taken else pc + 8, r2)
                res = ('if', val.flag, results[1], results[0])
                memo[key] = res
                return res
            raise AssertionError('unhandled %s at %x' % (i.disassemble(), pc))

    if flag_oracle is not None:
        return run_concrete(entry, flag_oracle)
    return go(entry, {})


def run_concrete(entry, oracle):
    regs = {}
    pc = entry
    steps = 0
    while True:
        steps += 1
        assert steps < 100000
        i = ins_at(pc)
        n = i.getOpcodeName()
        if step_simple(i, regs):
            pc += 4
            continue
        word_ = w(pc)
        rs = (word_ >> 21) & 31
        if n == 'jal':
            d = ins_at(pc + 4)
            step_simple(d, regs)
            regs[2] = 1 if oracle(regs[5]) else 0
            pc += 8
            continue
        if n == 'jr':
            d = ins_at(pc + 4)
            step_simple(d, regs)
            return regs[2]
        tgt = (pc + 4 + (s16(word_ & 0xffff) << 2)) & 0xffffffff
        likely = n in ('beql', 'bnel')
        if n == 'b':
            taken = True
        else:
            val = regs.get(rs, 0)
            taken = (val == 0) if n in ('beqz', 'beq', 'beql') else (val != 0)
        d = ins_at(pc + 4)
        if taken or not likely:
            step_simple(d, regs)
        pc = tgt if taken else pc + 8


def tree_eval(t, oracle):
    while t[0] == 'if':
        t = t[2] if oracle(t[1]) else t[3]
    return int(oracle(t[1])) if t[2] else t[1]


def emit_tree(t, ind, out):
    sp = '    ' * ind
    if t[0] == 'ret':
        if t[2]:
            out.append('%sreturn f.test(0x%x) ? 1 : 0;' % (sp, t[1]))
        else:
            out.append('%sreturn %d;' % (sp, t[1]))
        return
    _, flag, tt, ff = t
    if ff[0] == 'ret' and not ff[2]:
        out.append('%sif (!f.test(0x%x)) return %d;' % (sp, flag, ff[1]))
        emit_tree(tt, ind, out)
    elif tt[0] == 'ret' and not tt[2]:
        out.append('%sif (f.test(0x%x)) return %d;' % (sp, flag, tt[1]))
        emit_tree(ff, ind, out)
    else:
        out.append('%sif (f.test(0x%x)) {' % (sp, flag))
        emit_tree(tt, ind + 1, out)
        out.append('%s}' % sp)
        emit_tree(ff, ind, out)


def lcg_states():
    """Flag states used by the check: all clear, all set, then 6 LCG states (game LCG, bit 16 of each step)."""
    states = [set(), set(range(4000))]
    for s in range(1, 7):
        st = s * 0x1234567
        on = set()
        for fl in range(4000):
            st = (st * 0x19660d + 0x3c6ef35f) & 0xffffffff
            if (st >> 16) & 1:
                on.add(fl)
        states.append(on)
    return states


def gen_predicates():
    funcs = dispatch_funcs()
    assert len(funcs) == 81, len(funcs)
    lines = [HEADER, '// Included by native/game/progress/talk_predicates.cpp inside namespace baroque::game (anonymous).',
             '// Each block function receives the talk index (as FUN_001a0e60 passes it) and subtracts its base like the',
             '// original (addiu v0, a0, -base; sltiu at, v0, count); out-of-range indices return 0.', '']
    trees = {}
    prev_limit = 0
    total_cases = 0
    names = []
    for limit, f in funcs:
        pro = parse_prologue(f)
        name = 'pred%08x' % f
        names.append((prev_limit, limit, f, name))
        lines.append('// orig FUN_%08x (work/decompiled/%08x.c + disassembly; jump table %s) talk indices 0x%x..0x%x'
                     % (f, f, ('0x%x' % pro[2]) if pro else 'none', prev_limit, limit - 1))
        lines.append('int %s(const FlagView& f, uint32_t idx) {' % name)
        if pro is None:
            lines.append('    (void)f; (void)idx;')
            lines.append('    return 0;')
            lines.append('}')
            lines.append('')
            prev_limit = limit
            continue
        base, count, table = pro
        assert base == prev_limit, (hex(f), base, prev_limit)
        lines.append('    const uint32_t c = idx - 0x%xu;' % base if base else '    const uint32_t c = idx;')
        lines.append('    if (c >= 0x%xu) return 0;' % count)
        lines.append('    switch (c) {')
        for c in range(count):
            entry = w(table + 4 * c)
            t = run_case(entry)
            trees[base + c] = (entry, t)
            total_cases += 1
            lines.append('    case %d: {  // talk 0x%x (%d), code 0x%08x' % (c, base + c, base + c, entry))
            body = []
            emit_tree(t, 2, body)
            lines.extend(body)
            lines.append('    }')
        lines.append('    default: return 0;')
        lines.append('    }')
        lines.append('}')
        lines.append('')
        prev_limit = limit
    # dispatcher table (FUN_001a0e60 compare chain)
    lines.append('// FUN_001a0e60 compare chain: {limit, block function}')
    lines.append('struct PredBlock { uint32_t limit; int (*fn)(const FlagView&, uint32_t); uint32_t addr; };')
    lines.append('constexpr PredBlock kPredBlocks[%d] = {' % len(names))
    for lo, hi, f, name in names:
        lines.append('    {0x%x, &%s, 0x%08x},' % (hi, name, f))
    lines.append('};')
    open(os.path.join(OUT, 'talk_predicates.inc'), 'w', newline='\n').write('\n'.join(lines) + '\n')
    assert total_cases == TALK_COUNT, total_cases

    # verify trees against the concrete interpreter and produce the expected results
    states = lcg_states()
    exp = []
    for si, st in enumerate(states):
        oracle = (lambda s: (lambda fl: fl in s))(st)
        bits = []
        for idx in range(TALK_COUNT):
            entry, t = trees[idx]
            a = tree_eval(t, oracle)
            b = run_concrete(entry, oracle)
            assert a == b, (idx, si, a, b)
            bits.append(a)
        h = 0x811c9dc5
        for b in bits:
            h = ((h ^ b) * 0x01000193) & 0xffffffff
        exp.append((sum(bits), h, [i for i, b in enumerate(bits) if b][:8]))
    flags_used = sorted({fl for _, t in trees.values() for fl in tree_flags(t)})
    with open(os.path.join(CHECKS, 'progress_expected.inc'), 'w', newline='\n') as o:
        o.write(HEADER)
        o.write('// Predicate results per check flag state (0 all clear, 1 all set, 2..7 LCG states; see lcg_states()).\n')
        o.write('// {true count, FNV-1a over the 1590 results, first true indices}\n')
        o.write('struct PredExpected { int trueCount; uint32_t fnv; int first[8]; };\n')
        o.write('constexpr PredExpected kPredExpected[%d] = {\n' % len(exp))
        for cnt, h, first in exp:
            first = first + [-1] * (8 - len(first))
            o.write('    {%d, 0x%08x, {%s}},\n' % (cnt, h, ', '.join(str(x) for x in first)))
        o.write('};\n')
        o.write('constexpr int kPredFlagsUsed = %d;   // distinct flag ids tested by the 1590 predicates\n' % len(flags_used))
        o.write('constexpr int kPredFlagMax = 0x%x;\n' % max(flags_used))
    print('predicates: %d blocks, %d cases, %d distinct flags (max 0x%x)' % (len(funcs), total_cases, len(flags_used),
                                                                          max(flags_used)))
    for cnt, h, _ in exp:
        print('  state: %d true, fnv %08x' % (cnt, h))


def tree_flags(t):
    if t[0] == 'ret':
        return [t[1]] if t[2] else []
    return [t[1]] + tree_flags(t[2]) + tree_flags(t[3])


# ---------------------------------------------------------------- data tables
def i32(v):
    return v - 0x100000000 if v & 0x80000000 else v


def words(addr, n):
    return [w(addr + 4 * k) for k in range(n)]


def cstr(addr):
    return disasm.cstring(addr)


def id4(addr):
    b = disasm.read_bytes(addr, 4)
    return b.decode('latin1')


def emit_int_array(o, name, vals, ctype='int32_t', comment='', per_line=12, hexfmt=True):
    if comment:
        o.write('// %s\n' % comment)
    o.write('constexpr %s %s[%d] = {\n' % (ctype, name, len(vals)))
    for k in range(0, len(vals), per_line):
        chunk = vals[k:k + per_line]
        o.write('    %s,\n' % ', '.join((('0x%x' % v) if (hexfmt and v >= 0) else str(v)) for v in chunk))
    o.write('};\n')


