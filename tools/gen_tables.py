"""Emit ELF-resident game tables of SLUS_217.14 as C++ initialisers for native/data (namespace baroque::data).

Usage: python -I tools/gen_tables.py
Outputs (all regenerated, never hand-edited):
  native/data/tables/act_command_table.inc   66 {name, handler} from the static ctors 0x4c4ea0.. (table 0x48e600) + PTMFs 0x44b350
  native/data/tables/talk_table.inc          1590 {file, voiceNo, speakerId} at 0x457020 (FUN_001a73a0)
  native/data/tables/talk_window_rects.inc   float[12][2][4] at 0x4620e0 (+ text colours 0x462260)
  native/data/tables/texture_table.inc       286 {nameEN, groupEN, nameJP, groupJP} at 0x48a280 (FUN_00106090)
  native/data/tables/glyph_codes_jp.inc      1344 Shift-JIS codes at 0x48b470 (FUN_00112800/FUN_00112b30)
  native/data/tables/glyph_codes_en.inc      115 codes at 0x48bf00
  native/data/tables/glyph_unicode_{jp,en}.inc  the same codes decoded to Unicode (cp932) for sjisToUtf8
  native/data/tables/glyph_metrics_en.inc    115 {xofs, yofs, advance} at 0x48bff0 (FUN_00112e80), one per EN glyph
  native/data/tables/ascii_glyph_map.inc     the 8-byte full-width strings 0x42ca40..0x42cb10 used by FUN_00112e80
  native/checks/data_expected.inc            expected counts/histograms from work/game_formats_summary.json
"""
import json
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import disasm  # noqa: E402

OUT = os.path.join(ROOT, 'native', 'data', 'tables')
CHECKS = os.path.join(ROOT, 'native', 'checks')
HEADER = '// GENERATED by tools/gen_tables.py from SLUS_217.14 - do not edit.\n'

w = disasm.word
rb = disasm.read_bytes


def cstr_bytes(addr):
    return rb(addr, 512).split(b'\0')[0]


def clit(b):
    """C string literal from raw bytes (non-ASCII as \\x escapes, each escape closed by a literal break)."""
    out = ['"']
    for c in b:
        if c == 0x22:
            out.append('\\"')
        elif c == 0x5c:
            out.append('\\\\')
        elif 0x20 <= c < 0x7f:
            out.append(chr(c))
        else:
            out.append('\\x%02x""' % c)
    out.append('"')
    s = ''.join(out)
    return s.replace('""""', '""')


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(HEADER + text)


# ---------------------------------------------------------------- ACT command table (ctor scan)
def act_table():
    """Static ctors 0x4c4ea0..0x4cbe80 build 66 entries at 0x48e600 (0x18 each): 8 name bytes via lb from the
    string, then the PTMF {0,-1,fn} via lwc1/swc1 from 0x44b350+0x10*i. We decode lui/lb/sd to find each name."""
    names = {}
    regs, cur_min = {}, None
    for a in range(0x4c4e00, 0x4cbe80, 4):
        x = w(a)
        op, rs, rt, imm = x >> 26, (x >> 21) & 31, (x >> 16) & 31, x & 0xffff
        if imm >= 0x8000:
            imm -= 0x10000
        if op == 0x0f:  # lui
            regs[rt] = (x & 0xffff) << 16
        elif op == 0x20 and rs in regs:  # lb
            ad = regs[rs] + imm
            cur_min = ad if cur_min is None else min(cur_min, ad)
        elif op == 0x3f and rs in regs:  # sd
            tgt = regs[rs] + imm
            if 0x48e600 <= tgt < 0x48e600 + 66 * 0x18 and (tgt - 0x48e600) % 0x18 == 0 and cur_min is not None:
                names[(tgt - 0x48e600) // 0x18] = (cur_min, cstr_bytes(cur_min).decode('ascii'))
            cur_min = None
    assert len(names) == 66 and names[0][1] == 'End' and names[65][1] == 'NrmView', names
    lines = []
    for i in range(66):
        assert w(0x44b350 + 0x10 * i) == 0 and w(0x44b354 + 0x10 * i) == 0xffffffff
        lines.append('    {%-11s 0x%08x}, // %2d name @0x%06x, PTMF @0x%06x' % ('"%s",' % names[i][1], w(0x44b358 + 0x10 * i), i, names[i][0], 0x44b350 + 0x10 * i))
    write(os.path.join(OUT, 'act_command_table.inc'), '// {name, handler}: 66 entries of the dispatch table 0x48e600 (FUN_00146950), order = table index.\n' + '\n'.join(lines) + '\n')
    return [names[i][1] for i in range(66)]


# ---------------------------------------------------------------- talk table
def talk_table():
    lines, i = [], 0
    while True:
        a = 0x457020 + 12 * i
        p = w(a)
        if p == 0:
            break
        lines.append('    {%s, %s, %s},' % (clit(cstr_bytes(p)), clit(cstr_bytes(w(a + 4))), clit(cstr_bytes(w(a + 8)))))
        i += 1
    assert i == 0x636, i
    write(os.path.join(OUT, 'talk_table.inc'), '// {file, voiceNo, speakerId} x 1590 at 0x457020, NULL-terminated in the ELF (FUN_001a73a0).\n' + '\n'.join(lines) + '\n')
    # 12 layouts fill 0x4620e0..0x462260 (the colour table follows); TLK op 8 / trigger 0x6f use 0..10 (EN: C18A
    # 1/6/7/9/10, C08A 2, C19 5/10, C22A/B 8/9)
    rects = struct.unpack('<96f', rb(0x4620e0, 0x180))
    txt = '// float[layout 0..11][lang: 0 = EN (FUN_00114c80()==0), 1 = JP][x,y,w,h] at 0x4620e0..0x462260; indexed lang*0x10 + layout*0x20 (FUN_001a77c0).\n'
    txt += 'inline constexpr float kTalkWindowRects[12][2][4] = {\n'
    for layout in range(12):
        txt += '    {{%s}, {%s}},\n' % (', '.join('%.1ff' % v for v in rects[layout * 8:layout * 8 + 4]), ', '.join('%.1ff' % v for v in rects[layout * 8 + 4:layout * 8 + 8]))
    txt += '};\n// uint32 per language at 0x462260 (FUN_001a77c0 -> uRam0051ab14; text colour [I]).\n'
    txt += 'inline constexpr uint32_t kTalkTextColour[2] = {0x%06x, 0x%06x};\n' % (w(0x462260), w(0x462264))
    write(os.path.join(OUT, 'talk_window_rects.inc'), txt)


# ---------------------------------------------------------------- texture registry
def texture_table():
    lines = []
    for i in range(286):
        ws = [w(0x48a280 + 16 * i + 4 * k) for k in range(4)]
        lines.append('    {%s}, // %d' % (', '.join(clit(cstr_bytes(p)) if p else 'nullptr' for p in ws), i))
    assert w(0x48a280 + 16 * 286) == 0
    write(os.path.join(OUT, 'texture_table.inc'), '// {nameEN, groupEN, nameJP, groupJP} x 286 at 0x48a280 (FUN_00106090 / FUN_00106120).\n' + '\n'.join(lines) + '\n')


# ---------------------------------------------------------------- glyph tables
def glyph_tables():
    jp = rb(0x48b470, 0xa80)
    en = rb(0x48bf00, 0xe6)
    assert rb(0x48b470 + 0xa80, 2) == b'\0\0' and rb(0x48bf00 + 0xe6, 2) == b'\0\0'  # the loops' extra slot is 0
    for name, tbl, addr in (('jp', jp, 0x48b470), ('en', en, 0x48bf00)):
        codes = [(tbl[i] << 8) | tbl[i + 1] for i in range(0, len(tbl), 2)]
        rows = ['    ' + ', '.join('0x%04x' % c for c in codes[i:i + 12]) + ',' for i in range(0, len(codes), 12)]
        write(os.path.join(OUT, 'glyph_codes_%s.inc' % name), '// %d big-endian Shift-JIS codes at 0x%x (lead byte first); glyph index = position.\n' % (len(codes), addr) + '\n'.join(rows) + '\n')
        uni = []
        for i in range(0, len(tbl), 2):
            s = tbl[i:i + 2].decode('cp932', 'replace')
            uni.append(0xfffd if s == '�' else ord(s))
        rows = ['    ' + ', '.join('0x%04x' % c for c in uni[i:i + 12]) + ',' for i in range(0, len(uni), 12)]
        write(os.path.join(OUT, 'glyph_unicode_%s.inc' % name), '// Unicode (BMP) of each glyph code, decoded with cp932 (0xfffd = undecodable).\n' + '\n'.join(rows) + '\n')
    # One metric row per EN glyph: 115 x 12 bytes = 0x48bff0..0x48c554, where the next table (read by FUN_001144f0
    # at DAT_0048c560..) begins. The renderer's `glyph < 0x159` test is only an index guard (GAME_FORMATS.md says 345).
    rows = []
    n_en = len(en) // 2
    for i in range(n_en):
        x, y, adv = struct.unpack('<3f', rb(0x48bff0 + 12 * i, 12))
        assert all(v == 0.0 or 1e-3 <= abs(v) <= 64 for v in (x, y, adv)), (i, x, y, adv)
        rows.append('    {%rf, %rf, %rf}, // %d' % (x, y, adv, i))
    write(os.path.join(OUT, 'glyph_metrics_en.inc'), '// %d {xofs, yofs, advance} in 16-px units at 0x48bff0 (FUN_00112e80, EN proportional mode); one per EN glyph.\n' % n_en + '\n'.join(rows) + '\n')
    # ASCII -> full-width glyph strings used by FUN_00112e80 (8-byte strings; only the 2-byte code matters)
    amap = [('0', 0x42ca40), ('a', 0x42ca48), ('A', 0x42ca50), ('+', 0x42ca58), ('-', 0x42ca60), ('*', 0x42ca68),
            ('/', 0x42ca70), ('=', 0x42ca78), ('.', 0x42ca80), (',', 0x42ca88), (':', 0x42ca90), ("'", 0x42ca98),
            (';', 0x42caa0), ('\\', 0x42caa8), ('?', 0x42cab0), ('!', 0x42cab8), ('#', 0x42cac0), ('$', 0x42cac8),
            ('%', 0x42cad0), ('&', 0x42cad8), ('"', 0x42cae0), ('(', 0x42cae8), (')', 0x42caf0), ('<', 0x42caf8),
            ('>', 0x42cb00), ('@', 0x42cb08), ('|', 0x42cb10)]
    rows = []
    for ch, addr in amap:
        b = rb(addr, 8)
        assert b[2:] == b'\0' * 6, (ch, b)
        rows.append('    {%s, 0x%02x%02x}, // 0x%06x' % (clit(ch.encode()), b[0], b[1], addr))
    write(os.path.join(OUT, 'ascii_glyph_map.inc'), '// {ascii, sjisCode}: \'0\' = base of digits, \'a\'/\'A\' = base of letters; the rest map 1:1 (FUN_00112e80).\n' + '\n'.join(rows) + '\n')


# ---------------------------------------------------------------- expected values from the Python summary
def expected(act_names):
    s = json.load(open(os.path.join(ROOT, 'work', 'game_formats_summary.json'), encoding='utf-8'))
    a, p, t, e = s['act'], s['prm'], s['tlk'], s['evt']
    txt = '// Values copied from work/game_formats_summary.json (tools/game_formats.py) for Baroque-DataCheck.\n'
    txt += 'inline constexpr int kExpActFiles = %d;\ninline constexpr int kExpActActions = %d;\n' % (a['files'], a['total_actions'])
    hist = a['command_histogram']
    txt += 'inline constexpr int kExpActCommandHistogram[66] = { // table order\n    ' + ', '.join(str(hist.get(n, 0)) for n in act_names) + '};\n'
    txt += 'inline constexpr int kExpActCommandsTotal = %d;\n' % sum(hist.values())
    txt += 'inline constexpr int kExpPrmCharRecords = %d;\n' % p['prmchar_records']
    txt += 'inline constexpr int kExpPrmItemRecords[14] = {%s};\n' % ', '.join(str(v[3]) for v in p['prmitem_strides'].values())
    txt += 'inline constexpr int kExpTlkFiles = %d;\ninline constexpr int kExpTlkEnFiles = %d;\n' % (t['files'], t['en_files'])
    th = t['trigger_kind_histogram']
    txt += 'inline constexpr int kExpTlkTriggerHistogram[15] = { // kinds 0x65..0x73, EN files only\n    ' + ', '.join(str(th.get('0x%x' % k, 0)) for k in range(0x65, 0x74)) + '};\n'
    ntr = sum(len(r['triggers']) for r in t['scripts_en'].values())
    nlines = sum(r['lines'] for r in t['scripts_en'].values())
    txt += 'inline constexpr int kExpTlkEnTriggers = %d;\ninline constexpr int kExpTlkEnLines = %d;\n' % (ntr, nlines)
    txt += 'inline constexpr int kExpEvtFiles = %d;\n' % e['files']
    ev = e['events_en']
    txt += 'inline constexpr int kExpEvtEnCues = %d;\ninline constexpr int kExpEvtEnActors = %d;\ninline constexpr int kExpEvtEnLines = %d;\n' % (
        sum(v['cues'] for v in ev.values()), sum(v['actors'] for v in ev.values()), sum(v['lines'] for v in ev.values()))
    first = {}
    for v in ev.values():
        for k, n in v['cue_first_ops'].items():
            first[int(k)] = first.get(int(k), 0) + n
    txt += 'inline constexpr int kExpEvtEnCueFirstOps[][2] = { // {opcode, count} over EN files\n    ' + ', '.join('{%d, %d}' % kv for kv in sorted(first.items())) + '};\n'
    txt += 'inline constexpr const char* kExpExiChunks[7] = {%s};\ninline constexpr uint32_t kExpExiChunkSizes[7] = {%s};\n' % (
        ', '.join('"%s"' % c[0] for c in s['exi']['chunks']), ', '.join(str(c[1]) for c in s['exi']['chunks']))
    txt += 'inline constexpr uint32_t kExpAiSeqA = %d, kExpAiSeqB = %d;\ninline constexpr int kExpAiSeqRecords = %d;\n' % (s['aiseq']['a'], s['aiseq']['b'], len(s['aiseq']['chars']))
    txt += 'inline constexpr const char* kExpAiSeqIds[] = {%s};\n' % ', '.join('"%s"' % c for c in s['aiseq']['chars'])
    write(os.path.join(CHECKS, 'data_expected.inc'), txt)


def main():
    names = act_table()
    talk_table()
    texture_table()
    glyph_tables()
    expected(names)
    print('tables written to', OUT)


if __name__ == '__main__':
    main()
