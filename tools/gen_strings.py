"""Extract the localized string table (0x437480, 881 ids x {EN,JP}) and the front-end UI data tables
from SLUS_217.14 into C++ include files for the native port.

Usage: python -I tools/gen_strings.py
Writes: native/game/ui/strings_en.inc   (kStringTableEN / kStringTableJP, id numbering preserved)
        native/game/ui/ui_tables.inc    (texture registry, glyph tables, EN metrics, menu layout tables)
All bytes are emitted verbatim (Shift-JIS kept) using octal escapes so the C++ side sees the original bytes.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import disasm  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, 'native', 'game', 'ui')

STRING_TABLE = 0x437480
STRING_COUNT = 881          # work/reports/SCENES.md 0.8
TEXTURE_TABLE = 0x48a280
TEXTURE_COUNT = 286         # GAME_FORMATS.md 5
GLYPH_EN = 0x48bf00
GLYPH_EN_BYTES = 0xe7       # FUN_00112800 loop bound (115 codes + pad)
GLYPH_JP = 0x48b470
GLYPH_JP_BYTES = 0xa81      # 1344 codes
METRICS_EN = 0x48bff0
METRICS_COUNT = 0x159       # 345 x {xofs, yofs, advance}
ASCII_MAP = 0x42ca40        # 27 x 8-byte SJIS strings used by FUN_00112e80
CHAR_PAGES = 0x44ca70       # PTR_DAT_0044ca70: 4 pages x 106 pointers (NAME ENTRY)
MOVIE_TABLE = 0x46dec0      # FUN_00213840 movie index -> file name

LO, HI = 0x100000, 0x4e5b70  # ELF image range (RAM-backed pointers are emitted as "")


def c_escape(b):
    out = []
    for ch in b:
        if ch == 0x22:
            out.append('\\"')
        elif ch == 0x5c:
            out.append('\\\\')
        elif ch == 0x0a:
            out.append('\\n')
        elif 0x20 <= ch < 0x7f:
            out.append(chr(ch))
        else:
            out.append('\\%03o' % ch)
    return '"' + ''.join(out) + '"'


def cstr_bytes(addr, limit=1024):
    if not (LO <= addr < HI):
        return b''
    return disasm.read_bytes(addr, limit).split(b'\0')[0]


def f32(addr):
    return struct.unpack('<f', struct.pack('<I', disasm.word(addr)))[0]


def fmt_float(v):
    if v != v or abs(v) > 1e30:   # NaN / garbage beyond the real table rows: emit the raw bit pattern as 0
        return '0.0f'
    if v == int(v) and abs(v) < 1e7:
        return '%d.0f' % int(v)
    return repr(float(v)) + 'f'


def emit_floats(lines, name, addr, rows, cols):
    lines.append('// %s: %d x %d floats at 0x%06x' % (name, rows, cols, addr))
    lines.append('BAROQUE_TABLE_LINKAGE const float %s[%d][%d] = {' % (name, rows, cols))
    for r in range(rows):
        vals = [fmt_float(f32(addr + (r * cols + c) * 4)) for c in range(cols)]
        lines.append('    {%s},' % ', '.join(vals))
    lines.append('};')


def emit_flat_floats(lines, name, addr, count):
    lines.append('// %s: %d floats at 0x%06x' % (name, count, addr))
    vals = [fmt_float(f32(addr + i * 4)) for i in range(count)]
    lines.append('BAROQUE_TABLE_LINKAGE const float %s[%d] = {%s};' % (name, count, ', '.join(vals)))


def gen_strings():
    lines = ['// Generated by tools/gen_strings.py from SLUS_217.14 table 0x437480 (FUN_00114da0: table[id*2+lang]).',
             '// Do not edit. Ids are the original ids; entries whose pointer targets RAM (0x4e5c8c/0x4e5c90) are "".',
             '// clang-format off',
             '#define BAROQUE_STRING_COUNT %d' % STRING_COUNT]
    for lang, name in ((0, 'kStringTableEN'), (1, 'kStringTableJP')):
        lines.append('static const char* const %s[%d] = {' % (name, STRING_COUNT))
        for i in range(STRING_COUNT):
            p = disasm.word(STRING_TABLE + i * 8 + lang * 4)
            lines.append('    /* 0x%03x */ %s,' % (i, c_escape(cstr_bytes(p))))
        lines.append('};')
    lines.append('// clang-format on')
    return '\n'.join(lines) + '\n'


def gen_tables():
    L = ['// Generated by tools/gen_strings.py from SLUS_217.14 .data. Do not edit.',
         '// Included once by native/game/ui/ui_tables.cpp (BAROQUE_TABLE_LINKAGE empty); declarations in ui_tables.hpp.',
         '#ifndef BAROQUE_TABLE_LINKAGE',
         '#define BAROQUE_TABLE_LINKAGE static',
         '#endif',
         '// clang-format off']
    # Texture registry (GAME_FORMATS.md 5): {nameEN, group, nameJP, group} x 16 bytes
    L.append('// Texture registry 0x48a280: {EN path, JP path} per id (FUN_00106090 / FUN_00106120)')
    L.append('#define BAROQUE_TEXTURE_COUNT %d' % TEXTURE_COUNT)
    L.append('BAROQUE_TABLE_LINKAGE const char* const kTexturePaths[%d][2] = {' % TEXTURE_COUNT)
    for i in range(TEXTURE_COUNT):
        e = TEXTURE_TABLE + i * 16
        en = cstr_bytes(disasm.word(e))
        jp = cstr_bytes(disasm.word(e + 8))
        L.append('    /* 0x%03x */ {%s, %s},' % (i, c_escape(en), c_escape(jp)))
    L.append('};')
    # Glyph code tables
    g = disasm.read_bytes(GLYPH_EN, GLYPH_EN_BYTES)
    codes = [(g[i] << 8) | g[i + 1] for i in range(0, GLYPH_EN_BYTES - 1, 2)]
    L.append('// EN glyph codes 0x48bf00 (FUN_00112800 lookup, glyph index = position; SJIS lead<<8|trail)')
    L.append('#define BAROQUE_GLYPH_EN_COUNT %d' % len(codes))
    L.append('BAROQUE_TABLE_LINKAGE const unsigned short kGlyphCodesEN[%d] = {%s};' % (len(codes), ', '.join('0x%04x' % c for c in codes)))
    g = disasm.read_bytes(GLYPH_JP, GLYPH_JP_BYTES)
    codes = [(g[i] << 8) | g[i + 1] for i in range(0, GLYPH_JP_BYTES - 1, 2)]
    L.append('// JP glyph codes 0x48b470')
    L.append('#define BAROQUE_GLYPH_JP_COUNT %d' % len(codes))
    L.append('BAROQUE_TABLE_LINKAGE const unsigned short kGlyphCodesJP[%d] = {' % len(codes))
    for i in range(0, len(codes), 16):
        L.append('    ' + ', '.join('0x%04x' % c for c in codes[i:i + 16]) + ',')
    L.append('};')
    emit_floats(L, 'kGlyphMetricsEN', METRICS_EN, METRICS_COUNT, 3)
    # ASCII -> full-width mapping strings (FUN_00112e80): order as in the renderer's switch
    L.append('// ASCII mapping strings 0x42ca40..0x42cb10 (digits, a-z, A-Z, then punctuation + - * / = . , : \' ; \\ ? ! # $ % & " ( ) < > @ |)')
    vals = []
    for i in range(27):
        b = disasm.read_bytes(ASCII_MAP + i * 8, 2)
        vals.append('0x%04x' % ((b[0] << 8) | b[1]))
    L.append('BAROQUE_TABLE_LINKAGE const unsigned short kAsciiMapCodes[27] = {%s};' % ', '.join(vals))
    # NAME ENTRY character pages
    L.append('// NAME ENTRY character pages PTR_DAT_0044ca70: 4 pages x 106 SJIS codes (0 = end marker)')
    L.append('BAROQUE_TABLE_LINKAGE const unsigned short kNameEntryPages[4][106] = {')
    for p in range(4):
        row = []
        for i in range(106):
            ptr = disasm.word(CHAR_PAGES + (p * 106 + i) * 4)
            if ptr == 0:
                row.append('0')
            else:
                b = disasm.read_bytes(ptr, 2)
                row.append('0x%04x' % ((b[0] << 8) | b[1]))
        L.append('    {' + ', '.join(row) + '},')
    L.append('};')
    # Movie table
    L.append('// Movie index table 0x46dec0 (FUN_00213840)')
    names = []
    for i in range(29):
        p = disasm.word(MOVIE_TABLE + i * 4)
        s = cstr_bytes(p)
        if not s:
            break
        names.append(c_escape(s))
    L.append('#define BAROQUE_MOVIE_COUNT %d' % len(names))
    L.append('BAROQUE_TABLE_LINKAGE const char* const kMovieNames[%d] = {%s};' % (len(names), ', '.join(names)))
    # Layout tables (float rectangles) used by the front-end pages
    emit_floats(L, 'kTitleLogoPos', 0x48c680, 5, 4)        # FUN_00118c60
    emit_floats(L, 'kTitleLogoUv', 0x48c6d0, 5, 4)
    emit_flat_floats(L, 'kTitleCopyrightJP', 0x48c720, 8)
    emit_floats(L, 'kTitleCopyrightPosEN', 0x48c740, 4, 4)
    emit_floats(L, 'kTitleCopyrightUvEN', 0x48c780, 4, 4)
    emit_flat_floats(L, 'kTitlePressStart', 0x48c7c0, 8)
    emit_floats(L, 'kTitleLetterUv', 0x492090, 26, 4)      # FUN_00164a30 / FUN_00164d00
    emit_floats(L, 'kMenuFramePos', 0x493c80, 22, 4)       # FUN_001642d0 (tex 0x31)
    emit_floats(L, 'kMenuFrameUv', 0x493de0, 22, 4)
    emit_floats(L, 'kMenuFrame2Pos', 0x493f40, 61, 24)     # FUN_001664b0 (tex 0x2e), 6 variants x 4
    emit_floats(L, 'kMenuFrame2Uv', 0x495620, 61, 4)
    emit_floats(L, 'kMenuHelpBarPos', 0x4959f0, 6, 4)      # FUN_001664b0 (tex 0x25)
    emit_flat_floats(L, 'kMenuHelpBarUv', 0x495a50, 4)
    emit_floats(L, 'kNameEntryTabPos', 0x495a60, 4, 4)     # FUN_00169cd0 (tex 0x2e)
    emit_floats(L, 'kNameEntryTabUv', 0x495aa0, 4, 4)
    emit_floats(L, 'kConfigBarPos', 0x44bfb0, 9, 4)        # FUN_0015dcd0 (tex 0x2e)
    emit_floats(L, 'kConfigBarUv', 0x44c040, 9, 4)
    emit_floats(L, 'kConfigRowPos', 0x491c70, 10, 2)       # FUN_0015e9d0 item text positions
    emit_floats(L, 'kVolumeTable', 0x491cc0, 11, 3)        # FUN_0015da60 BGM/SE/voice volume steps
    emit_floats(L, 'kFileSlotPos', 0x49d260, 66, 8)        # FUN_00201e20 (tex 0x2f)
    emit_floats(L, 'kFileSlotUv', 0x49daa0, 66, 4)
    emit_floats(L, 'kFileCursorPos', 0x49dec0, 3, 4)
    emit_floats(L, 'kFileCursorUv', 0x49def0, 3, 4)
    emit_floats(L, 'kFileDungeonIconUv', 0x49df20, 10, 4)  # FUN_00204820 (JP layout only)
    emit_floats(L, 'kFileDifficultyUv', 0x49dfd0, 4, 4)
    emit_flat_floats(L, 'kFileDifficultyWidth', 0x49e010, 4)
    L.append('// Flag ids cleared/set by FUN_00178ad0 (new game wipe) and FUN_00179320 table 0x496200')
    L.append('BAROQUE_TABLE_LINKAGE const unsigned int kNewGameFlags[10] = {%s};' % ', '.join('0x%x' % disasm.word(0x495ae0 + i * 4) for i in range(10)))
    L.append('BAROQUE_TABLE_LINKAGE const unsigned int kGuardedFlags[10] = {%s};' % ', '.join('0x%x' % disasm.word(0x496200 + i * 4) for i in range(10)))
    L.append('// clang-format on')
    return '\n'.join(L) + '\n'


def main():
    # The string table is no longer compiled in: game/ui/strings.cpp reads it from the player's SLUS_217.14 at run
    # time. --strings still writes strings_en.inc (reference / comparison only; ignored by git, not built).
    os.makedirs(OUT_DIR, exist_ok=True)
    if '--strings' in sys.argv:
        with open(os.path.join(OUT_DIR, 'strings_en.inc'), 'w', encoding='ascii', newline='\n') as f:
            f.write(gen_strings())
        print('wrote strings_en.inc')
    with open(os.path.join(OUT_DIR, 'ui_tables.inc'), 'w', encoding='ascii', newline='\n') as f:
        f.write(gen_tables())
    print('wrote ui_tables.inc')


if __name__ == '__main__':
    main()
