"""Extract the data of the message box 0x53d730 and its window 0x51b010 (FUN_00164f40 / FUN_001655a0, FUN_001ac810,
FUN_001acdf0.., FUN_001ae900) from SLUS_217.14 into native/game/ui/message_box_tables.inc.

Usage: python -I tools/gen_msgbox_tables.py
Floats are emitted bit-exact, Shift-JIS strings as octal escapes (helpers shared with gen_menu_tables.py).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_menu_tables as g  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'native', 'game', 'ui', 'message_box_tables.inc')


def gen():
    L = ['// Generated by tools/gen_msgbox_tables.py from SLUS_217.14. Do not edit.', '// clang-format off']
    L.append('// included once by message_box.cpp inside an anonymous namespace')
    g.floats(L, 'kWinPiece', 0x492230, 0x3a, 8,
             'FUN_00164f40 / FUN_001655a0: {x, y, w, h} final then {x, y, w, h} at creation, tex 0x27')
    g.floats(L, 'kWinPieceUv', 0x492970, 0x3a, 4, 'FUN_00164f40 {u0, v0, u1, v1} (/128)')
    g.floats(L, 'kWinCentre', 0x492d10, 2, 4, 'FUN_00164f40 / FUN_001655a0 piece 0x51b0f8: final, creation {x, y, w, h} (tex 0x25)')
    g.flat_floats(L, 'kWinCentreUv', 0x492d30, 4, 'FUN_00164f40 piece 0x51b0f8 {u0, v0, u1, v1} (/128)')
    for name, addr, comment in (('kYesNoAll', 0x4627a0, 'FUN_001ac810 measured string'),
                                ('kYesNoYes', 0x4627b0, 'FUN_001ac810'),
                                ('kYesNoSlash', 0x4627b8, 'FUN_001ac810'),
                                ('kYesNoNo', 0x4627c0, 'FUN_001ac810'),
                                ('kPs2None', 0x4627c8, 'unused sub-messages of FUN_001acdf0 / FUN_001ae0e0'),
                                ('kUnknownSlot', 0x4627d8, 'FUN_001ae900 locked entry')):
        L.append('constexpr char %s[] = %s;   // 0x%06x %s' % (name, g.c_escape(g.cstr(addr)), addr, comment))
    L.append('// clang-format on')
    return '\n'.join(L).replace('BAROQUE_TABLE_LINKAGE const', 'constexpr') + '\n'


def main():
    with open(OUT, 'w', encoding='ascii', newline='\n') as fp:
        fp.write(gen())
    print('wrote', OUT)


if __name__ == '__main__':
    main()
